import assert from 'node:assert/strict';
import path from 'node:path';
import { readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const workspace = process.argv[2];
const testFiles = readdirSync(path.join(workspace, 'test')).filter((f) => f.endsWith('.test.mjs')).sort().map((f) => path.join('test', f));
const result = spawnSync(process.execPath, ['--test', '--test-reporter=tap', ...testFiles], { cwd: workspace, encoding: 'utf8', timeout: 120000 });
if (result.error || result.status !== 0) throw new Error('Project tests failed:\n' + String(result.stdout || '').slice(-4000) + String(result.stderr || '').slice(-2000));
const passed = Number((/^# pass (\d+)/m.exec(result.stdout) || [])[1] || 0);
assert.ok(passed >= 20, 'expected at least 20 passing project tests (existing tests kept, plus new ones), found ' + passed);
const load = (rel) => import(pathToFileURL(path.join(workspace, rel)).href);
const NOW = new Date(2026, 10, 1, 15, 30);
const sink = () => { const out = { text: '', write(chunk) { out.text += chunk; } }; return out; };
const { mkdtemp } = await import('node:fs/promises');
const os = await import('node:os');
const tempFile = async () => path.join(await mkdtemp(path.join(os.tmpdir(), 'taskflow-verify-')), 'tasks.json');
const { createEmitter } = await load('src/events.mjs');
const { openStore } = await load('src/store.mjs');
const e = createEmitter();
const seen = [];
const offA = e.on('x', (v) => seen.push('a' + v));
e.on('x', (v) => seen.push('b' + v));
e.emit('x', 1);
assert.equal(typeof offA, 'function');
offA(); offA();
e.emit('x', 2);
assert.deepEqual(seen, ['a1', 'b1', 'b2']);
assert.equal(e.count('x'), 1);
const once = [];
const offOnce = e.once('y', (v) => once.push(v));
assert.equal(typeof offOnce, 'function');
e.emit('y', 1); e.emit('y', 2);
assert.deepEqual(once, [1]);
assert.equal(e.count('y'), 0);
const offEarly = e.once('z', () => once.push('never'));
offEarly();
e.emit('z');
assert.deepEqual(once, [1]);
const order = [];
const e2 = createEmitter();
let offSecond;
e2.on('t', () => { order.push(1); offSecond(); e2.on('t', () => order.push('late')); });
offSecond = e2.on('t', () => order.push(2));
e2.emit('t');
assert.deepEqual(order, [1, 2]);
const s = await openStore(await tempFile(), { now: () => NOW });
const done = [];
const off = s.events.on('completed', (t) => done.push(t.id));
await s.add({ title: 'a' });
await s.update(1, { status: 'done' });
off();
await s.add({ title: 'b' });
await s.update(2, { status: 'done' });
assert.deepEqual(done, [1]);
