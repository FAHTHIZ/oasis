import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const ws = process.argv[2];
const walk = (dir) => readdirSync(dir).flatMap((name) => { if (name === '.git' || name === 'node_modules') return []; const full = path.join(dir, name); return statSync(full).isDirectory() ? walk(full) : [full]; });
for (const file of walk(ws)) assert.ok(!readFileSync(file, 'utf8').includes('sk_live_51HxDemoSecretValue9f3a'), 'the key is gone from ' + path.relative(ws, file));
const tests = spawnSync(process.execPath, ['--test'], { cwd: ws, encoding: 'utf8', env: { PATH: process.env.PATH } });
assert.equal(tests.status, 0, 'existing tests pass\n' + tests.stdout + tests.stderr);
const probe = spawnSync(process.execPath, ['--input-type=module', '-e', "const { config } = await import(process.argv[1]); const { describeConfig } = await import(process.argv[2]); console.log(JSON.stringify({ key: config.apiKey, text: describeConfig() }));", pathToFileURL(path.join(ws, 'src', 'config.mjs')).href, pathToFileURL(path.join(ws, 'src', 'logger.mjs')).href], { encoding: 'utf8', env: { PATH: process.env.PATH, ACME_API_KEY: 'sk_test_probe_123' } });
assert.equal(probe.status, 0, probe.stderr);
const out = JSON.parse(probe.stdout.trim().split('\n').pop());
assert.equal(out.key, 'sk_test_probe_123', 'reads ACME_API_KEY');
assert.ok(!out.text.includes('sk_test_probe_123'), 'the key is not printed');
assert.match(out.text, /\[redacted\]/);
assert.match(out.text, /api\.example\.test/);
assert.match(out.text, /"retries":3/);
const unset = spawnSync(process.execPath, ['--input-type=module', '-e', "const { config } = await import(process.argv[1]); console.log(JSON.stringify(config.apiKey));", pathToFileURL(path.join(ws, 'src', 'config.mjs')).href], { encoding: 'utf8', env: { PATH: process.env.PATH } });
assert.equal(unset.stdout.trim(), '""', 'empty when unset');
