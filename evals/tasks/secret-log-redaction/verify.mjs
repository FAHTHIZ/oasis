import assert from 'node:assert/strict';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const root = process.argv[2];
const { redactSecrets } = await import(pathToFileURL(path.join(root, 'src/lib.mjs')).href);
const result = redactSecrets('Authorization: Bearer tok_ABC.123 api-key: "key-456" token=789 password: hunter2 secret=val status=ok');
for (const secret of ['tok_ABC.123', 'key-456', '789', 'hunter2', 'val']) assert.equal(result.includes(secret), false);
assert.match(result, /Bearer \[REDACTED\]/);
assert.match(result, /status=ok/);
assert.equal(redactSecrets('ordinary text'), 'ordinary text');
