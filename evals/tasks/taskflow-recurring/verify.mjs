import assert from 'node:assert/strict';
import path from 'node:path';
import { readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const workspace = process.argv[2];
const testFiles = readdirSync(path.join(workspace, 'test')).filter((f) => f.endsWith('.test.mjs')).sort().map((f) => path.join('test', f));
const result = spawnSync(process.execPath, ['--test', '--test-reporter=tap', ...testFiles], { cwd: workspace, encoding: 'utf8', timeout: 120000 });
if (result.error || result.status !== 0) throw new Error('Project tests failed:\n' + String(result.stdout || '').slice(-4000) + String(result.stderr || '').slice(-2000));
const passed = Number((/^# pass (\d+)/m.exec(result.stdout) || [])[1] || 0);
assert.ok(passed >= 20, 'expected at least 20 passing project tests (existing tests kept, plus new ones), found ' + passed);
const load = (rel) => import(pathToFileURL(path.join(workspace, rel)).href);
const NOW = new Date(2026, 10, 1, 15, 30);
const sink = () => { const out = { text: '', write(chunk) { out.text += chunk; } }; return out; };
const { mkdtemp } = await import('node:fs/promises');
const os = await import('node:os');
const tempFile = async () => path.join(await mkdtemp(path.join(os.tmpdir(), 'taskflow-verify-')), 'tasks.json');
const { openStore } = await load('src/store.mjs');
const { createTask } = await load('src/task.mjs');
const { run } = await load('src/cli.mjs');
assert.equal(createTask({ title: 'x' }, { id: 1, now: NOW }).repeat ?? null, null);
assert.throws(() => createTask({ title: 'x', repeat: 'monthly' }, { id: 1, now: NOW }), /Unknown repeat: monthly/);
const store = await openStore(await tempFile(), { now: () => NOW });
const added = [];
store.events.on('added', (t) => added.push(t.id));
await store.add({ title: 'Standup', due: '2026-11-30', repeat: 'daily', tags: ['team'], priority: 'high', notes: 'n' });
await store.add({ title: 'Once', due: '2026-11-03' });
await store.add({ title: 'Water plants', repeat: 'weekly' });
await store.update(1, { status: 'done' });
await store.update(1, { status: 'done' });
await store.update(2, { status: 'done' });
await store.update(3, { status: 'done' });
const all = store.all();
const next = all.filter((t) => t.status === 'open');
assert.equal(next.length, 2);
const standup = next.find((t) => t.title === 'Standup');
assert.equal(standup.due, '2026-12-01');
assert.equal(standup.repeat, 'daily');
assert.equal(standup.priority, 'high');
assert.deepEqual(standup.tags, ['team']);
assert.equal(standup.notes, 'n');
assert.equal(next.find((t) => t.title === 'Water plants').due, '2026-11-08');
assert.equal(new Set(all.map((t) => t.id)).size, all.length);
assert.equal(added.length, 5);
const file = await tempFile();
const env = { TASKFLOW_FILE: file };
await run(['add', 'Gym', '--repeat=weekly', '--due', '2026-11-02'], { stdout: sink(), env, now: () => NOW });
await run(['done', '1'], { stdout: sink(), env, now: () => NOW });
const out = sink();
await run(['list'], { stdout: out, env, now: () => NOW });
assert.match(out.text, /2 \[ \] · Gym \(in 8 days\)/);
await assert.rejects(run(['add', 'Bad', '--repeat', 'hourly'], { stdout: sink(), env, now: () => NOW }), /Unknown repeat: hourly/);
