import assert from 'node:assert/strict';
import path from 'node:path';
import { readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const workspace = process.argv[2];
const testFiles = readdirSync(path.join(workspace, 'test')).filter((f) => f.endsWith('.test.mjs')).sort().map((f) => path.join('test', f));
const result = spawnSync(process.execPath, ['--test', '--test-reporter=tap', ...testFiles], { cwd: workspace, encoding: 'utf8', timeout: 120000 });
if (result.error || result.status !== 0) throw new Error('Project tests failed:\n' + String(result.stdout || '').slice(-4000) + String(result.stderr || '').slice(-2000));
const passed = Number((/^# pass (\d+)/m.exec(result.stdout) || [])[1] || 0);
assert.ok(passed >= 20, 'expected at least 20 passing project tests (existing tests kept, plus new ones), found ' + passed);
const load = (rel) => import(pathToFileURL(path.join(workspace, rel)).href);
const NOW = new Date(2026, 10, 1, 15, 30);
const sink = () => { const out = { text: '', write(chunk) { out.text += chunk; } }; return out; };
const { mkdtemp } = await import('node:fs/promises');
const os = await import('node:os');
const tempFile = async () => path.join(await mkdtemp(path.join(os.tmpdir(), 'taskflow-verify-')), 'tasks.json');
const { openStore } = await load('src/store.mjs');
const { run } = await load('src/cli.mjs');
const { readFile, writeFile } = await import('node:fs/promises');
const file = await tempFile();
const env = { TASKFLOW_FILE: file };
const say = async (...args) => { const out = sink(); await run(args, { stdout: out, env, now: () => NOW }); return out.text; };
assert.equal(await say('undo'), 'Nothing to undo.\n');
await say('add', 'one');
await say('add', 'two');
await say('done', '1');
assert.equal(await say('undo'), 'Undid last change.\n');
let data = JSON.parse(await readFile(file, 'utf8'));
assert.equal(data.version, 1);
assert.deepEqual(data.tasks.map((t) => [t.id, t.status]), [[1, 'open'], [2, 'open']]);
assert.equal(await say('undo'), 'Nothing to undo.\n');
await say('rm', '2');
assert.equal(await say('undo'), 'Undid last change.\n');
data = JSON.parse(await readFile(file, 'utf8'));
assert.deepEqual(data.tasks.map((t) => t.id), [1, 2]);
const legacy = await tempFile();
await writeFile(legacy, JSON.stringify({ version: 1, tasks: [{ id: 1, title: 'old', priority: 'normal', status: 'open', due: null, tags: [], notes: '', created: NOW.toISOString() }] }));
const s = await openStore(legacy, { now: () => NOW });
assert.equal(await s.undo(), false);
await s.add({ title: 'new' });
assert.equal(await s.undo(), true);
assert.deepEqual(s.all().map((t) => t.title), ['old']);
const reopened = await openStore(legacy, { now: () => NOW });
assert.deepEqual(reopened.all().map((t) => t.title), ['old']);
assert.equal(await reopened.undo(), false);
