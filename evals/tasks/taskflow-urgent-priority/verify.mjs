import assert from 'node:assert/strict';
import path from 'node:path';
import { readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const workspace = process.argv[2];
const testFiles = readdirSync(path.join(workspace, 'test')).filter((f) => f.endsWith('.test.mjs')).sort().map((f) => path.join('test', f));
const result = spawnSync(process.execPath, ['--test', '--test-reporter=tap', ...testFiles], { cwd: workspace, encoding: 'utf8', timeout: 120000 });
if (result.error || result.status !== 0) throw new Error('Project tests failed:\n' + String(result.stdout || '').slice(-4000) + String(result.stderr || '').slice(-2000));
const passed = Number((/^# pass (\d+)/m.exec(result.stdout) || [])[1] || 0);
assert.ok(passed >= 20, 'expected at least 20 passing project tests (existing tests kept, plus new ones), found ' + passed);
const load = (rel) => import(pathToFileURL(path.join(workspace, rel)).href);
const NOW = new Date(2026, 10, 1, 15, 30);
const sink = () => { const out = { text: '', write(chunk) { out.text += chunk; } }; return out; };
const { mkdtemp } = await import('node:fs/promises');
const os = await import('node:os');
const tempFile = async () => path.join(await mkdtemp(path.join(os.tmpdir(), 'taskflow-verify-')), 'tasks.json');
const { createTask, updateTask } = await load('src/task.mjs');
const { sortTasks, filterTasks } = await load('src/query.mjs');
const { formatTask } = await load('src/format.mjs');
const { run } = await load('src/cli.mjs');
const u = createTask({ title: 'Fire', priority: 'urgent' }, { id: 1, now: NOW });
assert.equal(u.priority, 'urgent');
assert.equal(updateTask(createTask({ title: 'x' }, { id: 2, now: NOW }), { priority: 'urgent' }).priority, 'urgent');
assert.throws(() => createTask({ title: 'x', priority: 'critical' }, { id: 3, now: NOW }), /Unknown priority/);
const list = [{ id: 1, priority: 'low' }, { id: 2, priority: 'urgent' }, { id: 3, priority: 'high' }, { id: 4, priority: 'normal' }, { id: 5, priority: 'urgent' }];
assert.deepEqual(sortTasks(list, 'priority').map((t) => t.id), [2, 5, 3, 4, 1]);
assert.deepEqual(filterTasks(list.map((t) => ({ ...t, status: 'open', tags: [] })), { priority: 'urgent' }).map((t) => t.id), [2, 5]);
assert.equal(formatTask({ id: 9, title: 'Fire', priority: 'urgent', status: 'open', due: null, tags: [] }, { now: NOW }), '  9 [ ] ‼ Fire');
assert.equal(formatTask({ id: 9, title: 'Fire', priority: 'high', status: 'open', due: null, tags: [] }, { now: NOW }), '  9 [ ] ! Fire');
const file = await tempFile();
const env = { TASKFLOW_FILE: file };
await run(['add', 'Low', '--priority', 'low'], { stdout: sink(), env, now: () => NOW });
await run(['add', 'Fix', 'prod', '--priority', 'urgent'], { stdout: sink(), env, now: () => NOW });
const out = sink();
await run(['list', '--sort', 'priority'], { stdout: out, env, now: () => NOW });
assert.equal(out.text, '  2 [ ] ‼ Fix prod\n  1 [ ]   Low\n');
