// Builds app/icons/lucide.svg: an SVG sprite of the Lucide icons (ISC, from
// the lucide-static package) that the web app references. Run it after adding
// an icon: `node scripts/vendor-icons.mjs`. test/app-icons.test.mjs fails when
// the committed sprite is out of date.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SPRITE_PATH = path.join(ROOT, 'app', 'icons', 'lucide.svg');

async function appSources(root) {
  const files = [];
  const walk = async (dir) => {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) await walk(full);
      else if (/\.(mjs|html)$/.test(entry.name)) files.push(full);
    }
  };
  await walk(path.join(root, 'app'));
  return files.sort();
}

/** Every Lucide icon id the app references, sorted. */
export async function usedIcons(root = ROOT) {
  const names = new Set();
  for (const file of await appSources(root)) {
    const text = await readFile(file, 'utf8');
    for (const match of text.matchAll(/icons\/lucide\.svg#([a-z0-9-]+)/g)) names.add(match[1]);
    for (const match of text.matchAll(/\bicon\('([a-z0-9-]+)'/g)) names.add(match[1]);
  }
  const { KIND_ICONS } = await import(pathToFileURL(path.join(root, 'app/core/icons.mjs')));
  const { PLUGINS } = await import(pathToFileURL(path.join(root, 'app/core/plugins.mjs')));
  for (const name of Object.values(KIND_ICONS)) names.add(name);
  for (const plugin of PLUGINS) names.add(plugin.icon);
  return [...names].sort();
}

/** The sprite text for `names`, read from node_modules/lucide-static. */
export async function buildSprite(names, root = ROOT) {
  const pkg = path.join(root, 'node_modules', 'lucide-static');
  const { version } = JSON.parse(await readFile(path.join(pkg, 'package.json'), 'utf8'));
  const symbols = [];
  for (const name of names) {
    let svg;
    try { svg = await readFile(path.join(pkg, 'icons', name + '.svg'), 'utf8'); } catch { throw new Error('Lucide has no icon named ' + name + ' (lucide.dev/icons)'); }
    const body = /<svg[^>]*>([\s\S]*?)<\/svg>/.exec(svg)[1].replace(/\s*\n\s*/g, '').replace(/\s*\/>/g, '/>');
    symbols.push('<symbol id="' + name + '" viewBox="0 0 24 24">' + body + '</symbol>');
  }
  return '<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide ' + version + ' (ISC License, https://lucide.dev/license). Generated by scripts/vendor-icons.mjs; do not edit. -->\n' + symbols.join('\n') + '\n</svg>\n';
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const names = await usedIcons();
  await writeFile(SPRITE_PATH, await buildSprite(names));
  console.log('Wrote ' + path.relative(ROOT, SPRITE_PATH) + ' with ' + names.length + ' Lucide icons.');
}
