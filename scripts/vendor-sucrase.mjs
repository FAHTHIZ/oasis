// Builds app/vendor/sucrase.mjs: Sucrase (MIT, https://github.com/alangpierce/sucrase)
// bundled by esbuild into one script, exported as source text. The sandbox
// runtime (app/core/sandbox.mjs) evaluates it inside the isolated worker so
// project files are transformed (ESM imports, TypeScript, JSX) only when
// required. Run it after upgrading sucrase: `node scripts/vendor-sucrase.mjs`.
// test/app-sandbox-sucrase.test.mjs fails when the committed file is stale.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SUCRASE_PATH = path.join(ROOT, 'app', 'vendor', 'sucrase.mjs');

/** The text of app/vendor/sucrase.mjs for the installed sucrase. */
export async function buildSucrase(root = ROOT) {
  const { build } = await import('esbuild');
  const { version } = JSON.parse(await readFile(path.join(root, 'node_modules', 'sucrase', 'package.json'), 'utf8'));
  const result = await build({
    stdin: { contents: "export { transform } from 'sucrase';", resolveDir: root },
    bundle: true, minify: true, write: false, format: 'iife', globalName: 'sucrase',
    platform: 'browser', target: 'es2019', legalComments: 'none', logLevel: 'silent'
  });
  const script = result.outputFiles[0].text.trim();
  return '// Sucrase ' + version + ' (MIT License, Copyright (c) 2012-2018 various contributors, see https://github.com/alangpierce/sucrase/blob/main/LICENSE).\n'
    + '// Generated by scripts/vendor-sucrase.mjs; do not edit. Evaluating SUCRASE_SOURCE defines a global `sucrase` with transform().\n'
    + 'export const SUCRASE_VERSION = ' + JSON.stringify(version) + ';\n'
    + 'export const SUCRASE_SOURCE = ' + JSON.stringify(script) + ';\n';
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const text = await buildSucrase();
  await writeFile(SUCRASE_PATH, text);
  console.log('Wrote ' + path.relative(ROOT, SUCRASE_PATH) + ' (' + Math.round(text.length / 1024) + ' KB).');
}
