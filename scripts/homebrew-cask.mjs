#!/usr/bin/env node
// Write the Homebrew tap files for a published release:
//   Casks/oasis.rb        desktop app (macOS):  brew install --cask fahthiz/oasis/oasis
//   Formula/oasis-cli.rb  CLI (macOS, Linux):   brew install fahthiz/oasis/oasis-cli
// after `brew tap fahthiz/oasis https://github.com/FAHTHIZ/oasis`.
// The release workflow runs this after publishing and commits the result to
// main; it can also be run by hand:
//   node scripts/homebrew-cask.mjs --version 1.1.0 --sums SHA256SUMS --source-sha <sha256 of the tag tarball>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CASK_PATH = path.join(ROOT, 'Casks', 'oasis.rb');
export const FORMULA_PATH = path.join(ROOT, 'Formula', 'oasis-cli.rb');
const REPOSITORY = 'FAHTHIZ/oasis';

// Map "<sha256>  ./OASIS-1.1.0-arm64.dmg" lines to { 'arm64': sha, 'x64': sha }.
export function dmgChecksums(sumsText, version) {
  const found = {};
  for (const line of String(sumsText || '').split(/\r?\n/)) {
    const match = line.trim().match(/^([0-9a-f]{64})\s+\*?(?:\.\/)?OASIS-(\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?)-(arm64|x64)\.dmg$/);
    if (match && match[2] === version) found[match[3]] = match[1];
  }
  return found;
}

export function renderCask(version, sums) {
  if (!/^\d+\.\d+\.\d+$/.test(String(version))) throw new Error('A stable x.y.z version is required, got ' + JSON.stringify(version));
  if (!sums.arm64 || !sums.x64) throw new Error('SHA256SUMS must list both OASIS-' + version + '-arm64.dmg and OASIS-' + version + '-x64.dmg');
  return `# Generated by scripts/homebrew-cask.mjs from the v${version} release SHA256SUMS.
# Do not edit by hand: the release workflow rewrites this file for each release.
cask "oasis" do
  arch arm: "arm64", intel: "x64"

  version "${version}"
  sha256 arm:   "${sums.arm64}",
         intel: "${sums.x64}"

  url "https://github.com/${REPOSITORY}/releases/download/v#{version}/OASIS-#{version}-#{arch}.dmg"
  name "OASIS"
  desc "Local-first AI coding agent with CLI, browser and desktop interfaces"
  homepage "https://github.com/FAHTHIZ/oasis"

  livecheck do
    url :url
    strategy :github_latest
  end

  # The app checks for stable releases itself and offers to install them.
  auto_updates true
  depends_on macos: ">= :ventura"

  app "OASIS.app"

  zap trash: [
    "~/Library/Application Support/OASIS",
    "~/Library/Logs/OASIS",
    "~/Library/Preferences/org.oasis.oss.plist",
    "~/Library/Saved Application State/org.oasis.oss.savedState",
  ]

  caveats <<~EOS
    OASIS is not code-signed yet. On first launch macOS may say it cannot verify
    the developer: open System Settings > Privacy & Security and choose
    "Open Anyway" for OASIS. Projects and settings in ~/.oasis are not removed
    by "brew uninstall --zap".
  EOS
end
`;
}

// The CLI formula installs the tagged source tarball with Homebrew's npm support
// (it runs `npm pack`, then a global install into libexec), on Homebrew's Node.
export function renderFormula(version, sourceSha) {
  if (!/^\d+\.\d+\.\d+$/.test(String(version))) throw new Error('A stable x.y.z version is required, got ' + JSON.stringify(version));
  if (!/^[0-9a-f]{64}$/.test(String(sourceSha || ''))) throw new Error('--source-sha must be the SHA-256 of the v' + version + ' source tarball');
  return `# Generated by scripts/homebrew-cask.mjs for the v${version} release.
# Do not edit by hand: the release workflow rewrites this file for each release.
class OasisCli < Formula
  desc "Local-first AI coding agent for the terminal and browser"
  homepage "https://github.com/FAHTHIZ/oasis"
  url "https://github.com/${REPOSITORY}/archive/refs/tags/v${version}.tar.gz"
  sha256 "${sourceSha}"
  license "Apache-2.0"

  livecheck do
    url :stable
    strategy :github_latest
  end

  depends_on "node"

  def install
    system "npm", "install", *std_npm_args
    bin.install_symlink libexec.glob("bin/*")
  end

  def caveats
    <<~EOS
      Run "oasis" inside a project folder; the first run opens provider setup.
      Update with "brew upgrade oasis-cli" ("oasis update" is for the script install).
    EOS
  end

  test do
    assert_match "OASIS #{version}", shell_output("#{bin}/oasis --version")
  end
end
`;
}

function main(argv) {
  const value = (flag) => { const index = argv.indexOf(flag); return index >= 0 ? argv[index + 1] : undefined; };
  const version = value('--version') || JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version;
  const sumsPath = value('--sums');
  if (!sumsPath) throw new Error('Usage: node scripts/homebrew-cask.mjs [--version x.y.z] --sums SHA256SUMS [--source-sha SHA256] [--out Casks/oasis.rb] [--formula-out Formula/oasis-cli.rb]');
  const write = (file, text) => {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    process.stdout.write('Wrote ' + path.relative(process.cwd(), file) + ' for OASIS ' + version + '\n');
  };
  write(value('--out') || CASK_PATH, renderCask(version, dmgChecksums(fs.readFileSync(sumsPath, 'utf8'), version)));
  const sourceSha = value('--source-sha');
  if (sourceSha) write(value('--formula-out') || FORMULA_PATH, renderFormula(version, sourceSha));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(process.argv.slice(2)); } catch (error) { process.stderr.write(error.message + '\n'); process.exit(1); }
}
